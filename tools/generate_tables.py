def feature(name):
    return FEATURES.get(name, "single-byte")


def cfg(name):
    """The `#[cfg(...)]` line gating `name`, or an empty string if always on."""
    f = feature(name)
    return "" if f is None else '#[cfg(feature = "{}")]\n'.format(f)


